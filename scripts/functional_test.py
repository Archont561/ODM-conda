def execute(arguments: list[str], directory: Path) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["OMP_NUM_THREADS"] = "1"
    completed = subprocess.run(arguments, cwd=directory, env=env, text=True, capture_output=True, timeout=60)
    if completed.returncode:
        raise AssertionError(f"Command failed ({completed.returncode}): {arguments}\n{completed.stdout}\n{completed.stderr}")
    return completed


def ply_header(path: Path) -> tuple[list[str], int, bytes]:
    data = path.read_bytes()
    marker = b"end_header\n"
    if not data.startswith(b"ply\n") or marker not in data:
        raise AssertionError("Output is not a valid LF-terminated PLY file")
    before, body = data.split(marker, 1)
    lines = before.decode("ascii").splitlines()
    count = next(int(line.split()[2]) for line in lines if line.startswith("element vertex "))
    return lines, count, body


def check_linkage(executable: Path) -> None:
    if sys.platform == "linux":
        completed = subprocess.run(["ldd", str(executable)], text=True, capture_output=True, timeout=30)
        result = completed.stdout + completed.stderr
        if completed.returncode or "not found" in result:
            raise AssertionError(f"Unresolved runtime dependency:\n{result}")


